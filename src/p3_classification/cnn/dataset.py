"""
dataset.py
----------
PyTorch Dataset for loading ERSP spectrograms from BCI-IV-2b.
Compatible with DataLoader for mini-batch training.

Usage:
    from src.p3_classification.cnn.dataset import ERSPDataset, build_loaders
    train_loader, val_loader = build_loaders(subjects=[1,2,3], suffix='T')
"""

import numpy as np
import torch
from sklearn.model_selection import train_test_split
from torch.utils.data import Dataset, DataLoader, Subset, random_split
from src.config import (
    DATA_PROC, SUBJECTS, BATCH_SIZE, VAL_SPLIT, RANDOM_SEED,
    N_CHANNELS, IMG_FREQ_BINS, IMG_TIME_BINS, TRAIN_SUFFIX, EVAL_SUFFIX
)


class ERSPDataset(Dataset):
    """
    ERSP spectrogram dataset for BCI-IV-2b.

    Loads .npz files generated by ersp.py and serves them
    as (X, y) tensors for PyTorch.

    Parameters
    ----------
    subjects : list of ints (1–9) with subjects to include
    suffix   : 'T' (training / sessions 1-3) or 'E' (evaluation / sessions 4-5)
    transform: optional transform applied to images (data augmentation)
    """

    def __init__(self,
                 subjects: list = None,
                 suffix: str = TRAIN_SUFFIX,
                 transform=None):
        if subjects is None:
            subjects = SUBJECTS

        self.transform = transform
        X_all, y_all = [], []

        for subj in subjects:
            tag = f"S{subj:02d}{suffix}"
            npz_path = DATA_PROC / f"{tag}-ersp.npz"

            if not npz_path.exists():
                print(f"  Warning: {npz_path.name} not found — subject skipped.")
                continue

            data = np.load(str(npz_path))
            X_all.append(data["X"])   # (N, C, F, T)
            y_all.append(data["y"])   # (N,)

        if not X_all:
            raise FileNotFoundError(
                "No ERSP files found. "
                "Run first: python src/p2_ersp/ersp.py"
            )

        self.X = torch.tensor(np.concatenate(X_all, axis=0), dtype=torch.float32)
        self.y = torch.tensor(np.concatenate(y_all, axis=0), dtype=torch.long)

        n_left  = (self.y == 0).sum().item()
        n_right = (self.y == 1).sum().item()
        print(f"  Dataset loaded: {len(self.X)} images "
              f"(left: {n_left}, right: {n_right}) — "
              f"shape: {tuple(self.X.shape)}")

    def __len__(self) -> int:
        return len(self.X)

    def __getitem__(self, idx: int):
        x = self.X[idx]
        y = self.y[idx]
        if self.transform is not None:
            x = self.transform(x)
        return x, y

    @property
    def n_classes(self) -> int:
        return int(self.y.max().item()) + 1

    @property
    def class_weights(self) -> torch.Tensor:
        """Inverse-frequency class weights (useful for imbalanced datasets)."""
        counts = torch.bincount(self.y)
        weights = 1.0 / counts.float()
        weights = weights / weights.sum()
        return weights


class _AugmentedSubset(Dataset):
    """Wraps a Subset and applies `transform` only to items drawn through
    this wrapper - used so training-split augmentation never leaks into the
    validation split, even though both are Subsets of the same underlying
    ERSPDataset (which itself has no transform set)."""

    def __init__(self, subset, transform):
        self.subset = subset
        self.transform = transform

    def __len__(self):
        return len(self.subset)

    def __getitem__(self, idx):
        x, y = self.subset[idx]
        if self.transform is not None:
            x = self.transform(x)
        return x, y


def build_loaders(subjects: list = None,
                  suffix_train: str = TRAIN_SUFFIX,
                  suffix_test: str = EVAL_SUFFIX,
                  batch_size: int = BATCH_SIZE,
                  val_split: float = VAL_SPLIT,
                  seed: int = RANDOM_SEED,
                  train_transform=None,
                  stratify: bool = True):
    """
    Build training, validation, and test DataLoaders.

    BCI-IV-2b protocol:
        - Training: sessions 1-3 (suffix='T'), with val_split reserved for validation
        - Test: sessions 4-5 (suffix='E')

    Parameters
    ----------
    subjects       : list of subjects (None = all)
    suffix_train   : 'T' for training sessions
    suffix_test    : 'E' for evaluation sessions
    batch_size     : mini-batch size
    val_split      : fraction of training set used for validation
    seed           : random seed for reproducibility
    train_transform: optional augmentation transform (see augmentation.py),
                     applied ONLY to the training split - never val/test.
    stratify       : if True (default), the train/val split preserves the
                     left/right class ratio (external review, C-3). This
                     matters more here than elsewhere in the project: the
                     *-ersp.npz files are written class-sorted by ersp.py
                     (all 'left' trials, then all 'right'), so the split is
                     taken over class-ordered indices. The previous
                     random_split did come out balanced in practice (measured
                     49.1% left in val for the pooled 9-subject set, all 9
                     subjects represented proportionally), so this is a
                     guarantee replacing a lucky seed, not a bug fix - but it
                     does change WHICH trials land in val, and therefore
                     early stopping. Checkpoints and metrics committed before
                     this change were trained with the unstratified split;
                     pass stratify=False to reproduce them exactly.

    Returns
    -------
    train_loader, val_loader, test_loader
    """
    if subjects is None:
        subjects = SUBJECTS

    print("\n── Loading training dataset ──")
    train_full = ERSPDataset(subjects=subjects, suffix=suffix_train)

    print("\n── Loading evaluation dataset ──")
    test_ds = ERSPDataset(subjects=subjects, suffix=suffix_test)

    # Train / validation split
    n_val   = int(len(train_full) * val_split)
    n_train = len(train_full) - n_val
    if stratify:
        y_all = train_full.y.numpy()
        train_idx, val_idx = train_test_split(
            np.arange(len(train_full)), test_size=n_val,
            stratify=y_all, random_state=seed,
        )
        train_ds = Subset(train_full, train_idx.tolist())
        val_ds   = Subset(train_full, val_idx.tolist())
    else:
        # Legacy unstratified split - reproduces checkpoints committed before
        # the stratified split became the default.
        generator = torch.Generator().manual_seed(seed)
        train_ds, val_ds = random_split(
            train_full, [n_train, n_val], generator=generator
        )
    if train_transform is not None:
        train_ds = _AugmentedSubset(train_ds, train_transform)

    train_loader = DataLoader(train_ds, batch_size=batch_size,
                              shuffle=True,  num_workers=0, pin_memory=False)
    val_loader   = DataLoader(val_ds,   batch_size=batch_size,
                              shuffle=False, num_workers=0, pin_memory=False)
    test_loader  = DataLoader(test_ds,  batch_size=batch_size,
                              shuffle=False, num_workers=0, pin_memory=False)

    print(f"\n  Sizes: train={n_train}, val={n_val}, test={len(test_ds)}")
    return train_loader, val_loader, test_loader


